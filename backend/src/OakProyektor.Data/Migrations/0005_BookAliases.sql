-- AliasKey es la forma NORMALIZADA (minúsculas, sin tildes, sin puntos ni espacios; «I»/«Primera de» → «1»): única en todo el canon, así que una clave
-- nunca apunta a dos libros. Alias es cómo se escribe normalmente. BookNumber es el número canónico (1 a 66), SIN clave foránea (no depende de ninguna Biblia).

