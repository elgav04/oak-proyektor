    AliasKey   TEXT NOT NULL PRIMARY KEY,
    BookNumber INTEGER NOT NULL CHECK (BookNumber BETWEEN 1 AND 66),
    Alias      TEXT NOT NULL
) WITHOUT ROWID;
CREATE INDEX IX_BookAliases_BookNumber ON BookAliases (BookNumber);

